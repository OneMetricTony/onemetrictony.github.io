  function getLang() {
    const p = new URLSearchParams(location.search).get('lang');
    if (p && LANGS.includes(p)) return p;
    const saved = localStorage.getItem('fira_lang');
    return LANGS.includes(saved) ? saved : 'en';
  }

  function apply(lang) {
    document.documentElement.lang = HTMLLANG[lang] || 'en';
    const d = DICT[lang] || DICT.en;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      const v = d[el.getAttribute('data-i18n')];
      if (v != null) el.innerHTML = v;
    });
    document.querySelectorAll('[data-lang-btn]').forEach(function (b) {
      b.classList.toggle('is-active', b.getAttribute('data-lang-btn') === lang);
    });
    // keep the chosen language across internal navigation — bake ?lang= into same-site links
    document.querySelectorAll('a[href]').forEach(function (a) {
      if (a.hasAttribute('data-lang-btn')) return;
      var href = a.getAttribute('href');
      if (!href || /^(https?:|mailto:|tel:|#)/i.test(href)) return;
      try {
        var u = new URL(href, location.href);
        if (u.origin !== location.origin) return;
        u.searchParams.set('lang', lang);
        var file = u.pathname.split('/').pop() || u.pathname;
        a.setAttribute('href', file + u.search + u.hash);
      } catch (e) {}
    });
    // swap localized images (e.g. the booth poster) by language
    document.querySelectorAll('img[data-src-en]').forEach(function (img) {
      var s = img.getAttribute('data-src-' + lang) || img.getAttribute('data-src-en');
      if (s) img.setAttribute('src', s);
    });
    try { localStorage.setItem('fira_lang', lang); } catch (e) {}
  }

  document.addEventListener('DOMContentLoaded', function () { apply(getLang()); });
